export function translate(text: string, language: Language): string {
  const exact = translations[text]?.[language];
  if (exact) return exact;
  let result = text;
  const entries = Object.entries(translations)
    .filter(([source, values]) => source.length >= 4 && Boolean(values[language]))
    .sort(([left], [right]) => right.length - left.length);
  for (const [source, values] of entries) {
    if (result.includes(source)) result = result.split(source).join(values[language]!);
  }
  return result;
}

