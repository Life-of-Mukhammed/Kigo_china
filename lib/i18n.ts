export function translateDom(root: ParentNode, language: Language) {
  const visit = (node: Node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const current = node.nodeValue || "";
      const cached = textCache.get(node);
      let source = cached && current === cached.rendered ? cached.source : current;
      if (language === "uz" && reverseUzbek.has(source)) source = reverseUzbek.get(source)!;
      const rendered = language === "uz" ? source : translate(source, language);
      textCache.set(node, { source, rendered });
      if (current !== rendered) node.nodeValue = rendered;
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    const element = node as Element;
    let cache = attributeCache.get(element);
    if (!cache) {
      cache = new Map();
      attributeCache.set(element, cache);
    }
    for (const name of ["placeholder", "aria-label", "title", "alt"]) {
      const current = element.getAttribute(name);
      if (current === null) continue;
      const cached = cache.get(name);
      let source = cached && current === cached.rendered ? cached.source : current;
      if (language === "uz" && reverseUzbek.has(source)) source = reverseUzbek.get(source)!;
      const rendered = language === "uz" ? source : translate(source, language);
      cache.set(name, { source, rendered });
      if (current !== rendered) element.setAttribute(name, rendered);
    }
    for (const child of Array.from(node.childNodes)) visit(child);
  };
  for (const child of Array.from(root.childNodes)) visit(child);
}

